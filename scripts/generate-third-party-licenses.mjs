import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, normalize, resolve, sep } from 'node:path';

const LICENSE_FILE_RE = /^(?:licen[cs]e|copying|notice)(?:[._-].*)?$/i;

function normalizeLicenseText(text) {
  return text
    .replace(/\r\n?/g, '\n')
    .split('\n')
    .map((line) => line.trimEnd())
    .join('\n')
    .trim();
}

function packageRootFromInput(input) {
  const absolute = resolve(input);
  const marker = `${sep}node_modules${sep}`;
  const markerIndex = absolute.lastIndexOf(marker);
  if (markerIndex < 0) return undefined;
  const packageParts = absolute.slice(markerIndex + marker.length).split(sep);
  const count = packageParts[0]?.startsWith('@') ? 2 : 1;
  if (packageParts.length < count) return undefined;
  return join(absolute.slice(0, markerIndex + marker.length), ...packageParts.slice(0, count));
}

function packageRecord(packageRoot) {
  const packageJsonPath = join(packageRoot, 'package.json');
  if (!existsSync(packageJsonPath)) return undefined;
  const metadata = JSON.parse(readFileSync(packageJsonPath, 'utf8'));
  const licenseFiles = readdirSync(packageRoot)
    .filter((name) => LICENSE_FILE_RE.test(name))
    .sort((a, b) => a.localeCompare(b));
  // The distributed WebP WASM codec carries its upstream codec notice below
  // the package root; it is part of the copied binary's license evidence.
  if (metadata.name === '@jsquash/webp') licenseFiles.push('codec/LICENSE.codec.md');
  let text;
  if (licenseFiles.length > 0) {
    text = licenseFiles
      .map(
        (name) =>
          `----- ${name} -----\n${normalizeLicenseText(readFileSync(join(packageRoot, name), 'utf8'))}`,
      )
      .join('\n\n');
  } else {
    const spdxPath = join(
      process.cwd(),
      'node_modules',
      'spdx-license-list',
      'licenses',
      `${metadata.license}.json`,
    );
    if (!metadata.license || !existsSync(spdxPath)) {
      throw new Error(`${metadata.name}@${metadata.version}: license/notice file が見つかりません`);
    }
    const spdx = JSON.parse(readFileSync(spdxPath, 'utf8'));
    text = `----- SPDX ${metadata.license} -----\n${normalizeLicenseText(spdx.licenseText)}`;
  }
  return { id: `${metadata.name}@${metadata.version}`, text };
}

/** Generate the license bundle for packages that are actually embedded in dist assets. */
export function generateThirdPartyLicenses(inputs, extraPackageRoots = []) {
  const packageRoots = new Set(extraPackageRoots.map((root) => resolve(root)));
  for (const input of inputs) {
    const packageRoot = packageRootFromInput(input);
    if (packageRoot) packageRoots.add(normalize(packageRoot));
  }

  const records = [...packageRoots]
    .map(packageRecord)
    .filter(Boolean)
    .sort((a, b) => a.id.localeCompare(b.id));
  const groups = new Map();
  for (const record of records) {
    const hash = createHash('sha256').update(record.text).digest('hex');
    const group = groups.get(hash) ?? { packages: [], text: record.text };
    group.packages.push(record.id);
    groups.set(hash, group);
  }

  const sections = [...groups.values()]
    .sort((a, b) => a.packages[0].localeCompare(b.packages[0]))
    .map(
      (group) =>
        `================================================================================\n` +
        `Packages: ${group.packages.join(', ')}\n` +
        `================================================================================\n\n` +
        `${group.text}\n`,
    );
  const output = [
    'THIRD-PARTY SOFTWARE LICENSES',
    '',
    'This file is generated from the license and notice files of packages embedded in the',
    'note-md extension, CLI, Webview bundles, WASM modules, stylesheets, and fonts.',
    'Do not edit this file manually.',
    '',
    ...sections,
  ].join('\n');
  writeFileSync('docs/third-party-licenses.txt', output, 'utf8');
}
